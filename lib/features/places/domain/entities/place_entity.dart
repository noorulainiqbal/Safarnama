class PlaceEntity {
  final String id;
  final String name;
  final String description;
  final String imageUrl;
  final String location;
  final double rating;
  final double price;

  PlaceEntity({
    required this.id,
    required this.name,
    required this.description,
    required this.imageUrl,
    required this.location,
    required this.rating,
    required this.price,
  });
}
